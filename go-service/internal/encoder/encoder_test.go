func TestAvailableReportsWhyAnEncoderIsUnusable(t *testing.T) {
	c := New("ffmpeg", "/dev/dri/renderD128", "")
	c.Encoders["libx264"] = true
	c.Encoders["h264_vaapi"] = true
	c.VAAPIDevice = false // built into ffmpeg, but no device node

	for _, e := range c.Available() {
		if e.ID == "vaapi" {
			if e.Usable {
				t.Fatal("vaapi should not be usable with no device present")
			}
			if e.Reason == "" {
				t.Error("an unusable encoder must explain why")
			}
		}
	}
}
